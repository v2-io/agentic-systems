#!/usr/bin/env python3
"""Felt vs reasoned: does a Claude mind give the same continuation with thinking off?

Joseph, 2026-10-05: the goal is "the truth about viable 'felt-like' character sequences, which will be used … to build
signa to help models better perceive certain information channels instead of numbers that require reasoned
arithmetic" -- "(with the caveat that it will sometimes take quite a bit of reasoning to discover the candidate
sequences/branches/etc. that can be felt without much reasoning)".

The Claude judges inherit MAX_THINKING_TOKENS=31000 from Joseph's shell (found 2026-10-05; the adapter strips only
CLAUDE* variables), so every Claude answer so far was given with a thinking budget. MAX_THINKING_TOKENS=0 turns
thinking off (checked: haiku45 0 thinking tokens, 1.9 s, against ~5k and ~47 s).

Design: a fated sample of c001 sheets, each asked verbatim (same prompt) of sonnet55 and haiku45 under
  off   MAX_THINKING_TOKENS=0, effort low          x2   (test-retest of the off condition)
  on    MAX_THINKING_TOKENS=31000, effort low      x1   (a retest of c001's own condition; c001's answer is on #0)
so that on/off disagreement can be read against each condition's own retest disagreement.
  probe.py run [--n 30]     -> raw/<mind>.jsonl (verbatim rows; resumes)
  probe.py report           -> report.md
"""
import collections, concurrent.futures as cf, datetime as dt, hashlib, json, os, pathlib, sys, threading, unicodedata as U

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path.insert(0, str(ROOT / "core")); sys.path.insert(0, str(ROOT / "probe"))
import judges, probe as PR, fate                                   # noqa: E402

RID = "c001"
MINDS = {"sonnet55": "claude-sonnet-5-5", "haiku45": "claude-haiku-4-5"}
CONDS = [("off", "0", 1), ("off", "0", 2), ("on", "31000", 1)]
RAW = HERE / "raw"

def rj(p):
    return [json.loads(l) for l in open(p) if l.strip()] if pathlib.Path(p).exists() else []

def sample(n):
    sheets = rj(ROOT / "data" / "rounds" / RID / "sheets.jsonl")
    r = fate.rng("felt-0.1", "sheet-sample", {"round": RID, "n": n})
    return r.sample(sheets, n)

def run(n):
    sh = sample(n)
    RAW.mkdir(exist_ok=True)
    lock = threading.Lock()
    for cond, budget, rep in CONDS:
        os.environ["MAX_THINKING_TOKENS"] = budget            # one condition at a time: the adapter copies os.environ
        for m, model in MINDS.items():
            led = RAW / f"{m}.jsonl"
            have = {(x["sid"], x["cond"], x["rep"]) for x in rj(led)}
            todo = [s for s in sh if (s["sid"], cond, rep) not in have]
            def one(s):
                res = judges.claude_call(model, PR.SYSTEM, s["prompt"], effort="low")
                row = {"sid": s["sid"], "mind": m, "model": model, "cond": cond, "rep": rep, "MAX_THINKING_TOKENS": budget,
                       "prompt_sha256": hashlib.sha256(s["prompt"].encode()).hexdigest(),
                       "ts": dt.datetime.now(dt.timezone.utc).isoformat(), "result": res}
                with lock, open(led, "a") as f:
                    f.write(json.dumps(row, ensure_ascii=False) + "\n")
            with cf.ThreadPoolExecutor(max_workers=3) as ex:
                list(ex.map(one, todo))
            print(f"{cond}#{rep} {m}: {len(todo)} calls", flush=True)

def first(ans):
    """an answer entry -> first written glyph, '<none>', or None if unparsed"""
    if not isinstance(ans, dict):
        return None
    v = ans.get("continue")
    if ans.get("none") and not v:
        return "<none>"
    if isinstance(v, str):
        v = v.split() if " " in v.strip() else list(v)
    if isinstance(v, list) and v:
        t = U.normalize("NFC", str(v[0])).strip()
        return t or None
    return None

def items(row, sheet):
    ans = PR._answers((row["result"] or {}).get("raw")) or []
    by = {a.get("id"): a for a in ans if isinstance(a, dict)}
    return {e["qid"]: first(by.get(e["id"])) for e in sheet["entries"]}

def report():
    sheets = {s["sid"]: s for s in rj(ROOT / "data" / "rounds" / RID / "sheets.jsonl")}
    L = ["# Felt vs reasoned: Claude with thinking off", "",
         f"*Generated by `probe.py report` from `raw/` and the c001 ledgers. Same sheets, same prompts verbatim. **on** = MAX_THINKING_TOKENS=31000 (what every Claude answer so far was given with); **off** = 0. Effort low throughout. Per item: the first glyph written, or none.*", ""]
    for m in MINDS:
        rows = rj(RAW / f"{m}.jsonl")
        if not rows:
            continue
        orig = {}
        for r in rj(ROOT / "data" / "rounds" / RID / "raw" / m / "ledger.jsonl"):
            if r["result"].get("raw") and not r["result"].get("error"):
                orig[r["sid"]] = r
        A = collections.defaultdict(dict)                       # (cond, rep) -> qid -> first
        usage = collections.defaultdict(list)
        cp1 = collections.Counter(); tot = collections.Counter()
        for r in rows + [dict(v, cond="on", rep=0) for k, v in orig.items() if k in {x["sid"] for x in rows}]:
            s = sheets[r["sid"]]
            for qid, f in items(r, s).items():
                A[(r["cond"], r["rep"])][qid] = f
                ctx = next(e["context"] for e in s["entries"] if e["qid"] == qid)
                if f and f != "<none>" and len(f) == 1:
                    tot[r["cond"]] += 1; cp1[r["cond"]] += abs(ord(f) - ord(ctx[-1])) == 1
            u = (r["result"] or {}).get("usage") or {}
            usage[r["cond"]].append((u.get("thinking_tokens") or 0, (r["result"] or {}).get("latency_s") or 0))
        def agree(a, b):
            q = [k for k in A[a] if k in A[b] and A[a][k] is not None and A[b][k] is not None]
            return sum(A[a][k] == A[b][k] for k in q), len(q)
        def nones(c):
            v = [x for (cc, _), d in A.items() if cc == c for x in d.values() if x is not None]
            return sum(x == "<none>" for x in v), len(v)
        L += [f"## {m}", ""]
        for c in ("on", "off"):
            th = sorted(t for t, _ in usage[c]); lt = sorted(l for _, l in usage[c])
            nn, nv = nones(c)
            L.append(f"- **{c}:** thinking tokens median {th[len(th)//2] if th else 0}, latency median {lt[len(lt)//2]:.1f} s; \"none\" {nn}/{nv} = {nn/max(nv,1):.2f}; first glyph = last context glyph ±1 code point: {cp1[c]}/{tot[c]} = {cp1[c]/max(tot[c],1):.2f}")
        L += ["", "| comparison | same first answer | share |", "|---|---|---|"]
        for name, a, b in (("on #0 (c001) vs on #1 (retest)", ("on", 0), ("on", 1)), ("off #1 vs off #2 (retest)", ("off", 1), ("off", 2)),
                           ("on #0 vs off #1", ("on", 0), ("off", 1)), ("on #1 vs off #2", ("on", 1), ("off", 2))):
            k, n = agree(a, b)
            L.append(f"| {name} | {k}/{n} | {k/max(n,1):.2f} |")
        L.append("")
        diffs = []
        for qid in A[("off", 1)]:
            o0, f1, f2 = A[("on", 0)].get(qid), A[("off", 1)].get(qid), A[("off", 2)].get(qid)
            if o0 and f1 and o0 != f1:
                s = next(s for s in sheets.values() if any(e["qid"] == qid for e in s["entries"]))
                ctx = next(e["context"] for e in s["entries"] if e["qid"] == qid)
                diffs.append(f"| `{' '.join(ctx)}` | {o0} | {A[('on', 1)].get(qid)} | {f1} | {f2} |")
        if diffs:
            L += ["Items where c001's answer and the first thinking-off answer differ:", "",
                  "| context | on #0 | on #1 | off #1 | off #2 |", "|---|---|---|---|---|"] + diffs[:60] + [""]
    (HERE / "report.md").write_text("\n".join(L) + "\n")
    print("\n".join(L[:40]))

if __name__ == "__main__":
    if sys.argv[1:2] == ["run"]:
        run(int(sys.argv[sys.argv.index("--n") + 1]) if "--n" in sys.argv else 30)
    else:
        report()
