#!/usr/bin/env python3
"""A read-off (concern 5): CATALOG-GIVEN.md, the givens and what the minds did with them.

A given is an order that exists before any mind answers (catalog/givens.py has the definition and its sources). This
page lists every given in data/unicode/givens.json, and every catalog record that walks one (catalog build 5's given
relation, from catalog/given_walk.py), with the catalog's recognition beside it. CATALOG-VIEW.md shows the runs that
aren't given walks; together the two pages cover every recognised run. Nothing reads this page back.

Usage: python3 report/given.py   (needs psql-18 and the database empirica_glyph_sequence)
"""
import collections, json, pathlib, subprocess, sys

HERE = pathlib.Path(__file__).resolve()
ROOT = HERE.parents[1]
sys.path.insert(0, str(ROOT / "catalog"))
import given_walk as GW                                     # noqa: E402

DB = "empirica_glyph_sequence"
SHOW_MAX = 400          # positions shown inline per given; longer ones (Hangul's 11,172 syllables) are cut, with the
                        # count, and are whole in data/unicode/givens.json (a display choice, chosen without evidence)

def q(sql):
    r = subprocess.run(["psql-18", "-d", DB, "-Atq", "-c", sql], capture_output=True, text=True)
    if r.returncode:
        sys.exit(f"given.py: psql-18 failed: {r.stderr.strip()}")
    return [json.loads(l) for l in r.stdout.splitlines() if l.strip()]

def code(s):
    s = s.replace("|", "\\|")
    fence = "``" if "`" in s else "`"
    pad = " " if s.startswith("`") or s.endswith("`") else ""
    return f"{fence}{pad}{s}{pad}{fence}"

def seq(positions, sep=""):
    cut = positions[:SHOW_MAX]
    s = sep.join(p[0] for p in cut)
    return code(s) + (f" … ({len(positions):,} in all)" if len(positions) > SHOW_MAX else "")

def main():
    givens, dress, pos, versions = GW.load()
    man = (q("select doc from catalog.manifest") or [{}])[0]
    rows = q("select row_to_json(r) from (select glyphs, length, recognised, r_strength, r_sd, r_bf, r_families, sources, "
             "given_kind, given_id, given_label, given_dresses, given_step from catalog.records where given_kind is not null) r")
    n_records = q("select count(*) from catalog.records")[0]
    n_rec = q("select count(*) from catalog.records where recognised")[0]

    by_kind = collections.Counter(r["given_kind"] for r in rows)
    by_kind_rec = collections.Counter(r["given_kind"] for r in rows if r["recognised"])
    asked = lambda r: "asked whole" in (r["sources"] or [])
    by_kind_asked = collections.Counter(r["given_kind"] for r in rows if asked(r))

    L = ["# The givens", "",
         f"*Generated by `report/given.py` from the catalog in Postgres (build `{man.get('build', '?')}`, model `{man.get('model', '?')}`) and `data/unicode/givens.json` (ICU {versions['icu']}, its Unicode {versions['icu_unicode']}; characters kept only if assigned in Unicode {versions['unicode_python']}). A read-off: nothing reads it back. `CATALOG-VIEW.md` shows the recognised runs that aren't given walks; this page shows the ones that are, and every given.*", "",
         "## What a given is", "",
         "Joseph (2026-10-06): an order that is *\"contiguous, [has] a known canonical lexical ordering, known total order, same stylistic class ... implies a 'ready to use' sequence by design, with shifting, mirroring, and cycling all implied, probably as well as regular n-step sequences\"*. A run that walks one is reading a known order, not finding one, so probing turns toward runs that aren't given walks (Joseph: *\"we'll focus on probing things that aren't given\"*), and these runs stay in the catalog as data.", "",
         "Every given here is taken from Unicode's own data (`catalog/givens.py`):", "",
         "- **Alphabets:** each language's standard letters in CLDR (its exemplar set, through ICU), in that language's collation order, upper and lower case where the script has case. Two readings of membership are kept. *Letters:* every listed letter in full sort order (Russian `е ё ж`). *Base:* the letters that collation treats as distinct, the rest as forms of them (Spanish `á` is a form of `a`; `ñ` is its own letter). A language's letters are split by script (Japanese: hiragana, katakana).",
         "- **Numbers:** every character with a Unicode numeric value, grouped by its dress, ordered by value: digits in every script, circled 0–50 across three blocks, Roman numerals, vulgar fractions, superscripts.",
         "- **Dresses:** every letter in another style (bold, circled, fullwidth, superscript, fraktur…) maps to its base letter through Unicode's compatibility decomposition, or through its name where Unicode leaves it undecomposed (negative circled and squared letters, regional indicators, tags). The holes in the Mathematical Alphanumeric block are filled from NamesList's own cross-references (reserved U+1D455 → `ℎ` PLANCK CONSTANT), so `ℭ` and `ℎ` join their alphabets.", "",
         "**A run is a walk over a given** (`catalog/given_walk.py`) when its positions in one given are: a **window** (consecutive, one direction); **rotated** (consecutive around the given's end: `8 9 0 1`); a **stride** (a constant step: `B D F`, or a constant step in value: `⅛ ¼ ⅜ ½`); **dress** (one position in several dresses: `1 ¹ ① 𝟏`); a **dress-window** (consecutive, held across dresses: `2 ➋ 3 ➌`); or a **reflection** (consecutive with one turnaround). A run that skips a position (`Ο Π Ρ Τ Υ` without `Σ`) is not given. For letters, the alphabet is the most widely used one that holds every letter of the run (so `ñ` brings in Spanish and `ё` Russian, but a rare alphabet can't make an arbitrary run regular).", "",
         "**Decisions, each with its reason** (open to revision):", "",
         "- **Han is excluded.** Han characters have no ordering intrinsic to the set: their collation order is a convention (pinyin, stroke, radical) that differs by locale. Every other script's letters have a standard enumeration, syllabaries and Hangul syllables included.",
         "- **A dress run has a given set but not a given order.** `1 ¹ ① 𝟏` shows one number in several dresses, and no order among dresses is known. It's listed here, as a walk over the given set, and marked by its kind.",
         "- **Known gaps in the sources.** CLDR lists Korean's letters as syllables, so the jamo order (`ㄱ ㄴ ㄷ`, `ㅏ ㅐ ㅑ`) isn't a given here. `🔟` (KEYCAP TEN) has no Unicode numeric value, so a run that reaches for it isn't a given walk.", "",
         "## What the minds did with givens", "",
         f"Of {n_records:,} catalog records, **{len(rows):,} walk a given**. Of the {n_rec:,} records the catalog recognises, **{sum(by_kind_rec.values()):,}** do ({sum(by_kind_rec.values()) / max(n_rec, 1):.0%}).", "",
         "| kind | records | asked whole | recognised |", "|---|---|---|---|"]
    for k in GW.KINDS:
        L.append(f"| {k} | {by_kind[k]} | {by_kind_asked[k]} | {by_kind_rec[k]} |")
    L += ["", "### Recognised walks, by given", "",
          "*Each given's recognised walks, longest first. **R**: the catalog's recognition strength ± sd and its Bayes factor. **yes/n**: per family. **dresses**: the styles the run uses (\"plain\" is the base letters).*", ""]
    rec = [r for r in rows if r["recognised"]]
    by_given = collections.defaultdict(list)
    for r in rec:
        by_given[r["given_label"]].append(r)
    for lab, rs in sorted(by_given.items(), key=lambda kv: (-len(kv[1]), kv[0])):
        rs.sort(key=lambda r: (-r["length"], -(r["r_strength"] or 0), r["glyphs"]))
        L += [f"#### {lab} ({len(rs)})", "", "| run | n | kind | step | dresses | R | BF | yes/n |", "|---|---|---|---|---|---|---|---|"]
        for r in rs:
            fam = " ".join(f"{f[:2]} {v.get('yes')}/{v.get('n')}" for f, v in sorted((r["r_families"] or {}).items()))
            st = r["given_step"]
            st = ("–" if st is None else (f"{st:g}"))
            L.append(f"| {code(r['glyphs'])} | {r['length']} | {r['given_kind']} | {st} | {', '.join(r['given_dresses'] or [])} | "
                     f"{(r['r_strength'] or 0):+.2f} ± {(r['r_sd'] or 0):.2f} | {r['r_bf']:.3g} | {fam or '–'} |")
        L.append("")
    nrec = [r for r in rows if not r["recognised"]]
    L += ["### Walks not recognised (yet)", "",
          f"{len(nrec):,} records walk a given without being recognised: {sum(1 for r in nrec if asked(r)):,} asked whole and not recognised, the rest never asked whole (they come from walks, strongest paths, triad chains and seeds). By kind: "
          + ", ".join(f"{k} {n}" for k, n in collections.Counter(r['given_kind'] for r in nrec).most_common()) + ".", ""]

    # ---- the givens in full
    L += ["## Every given", "", f"*{len(givens):,} givens. Positions longer than {SHOW_MAX} are cut here and whole in `data/unicode/givens.json`.*", "",
          "### Numbers", "", "*One given per dress, in numeric value. A value held by several characters of one dress shows its first.*", "",
          "| dress | n | values |", "|---|---|---|"]
    nums = sorted((g for g in givens.values() if g["kind"] == "number"), key=lambda g: (-len(g["positions"]), g["dress"]))
    for g in nums:
        L.append(f"| {g['dress']} | {len(g['positions'])} | {seq(g['positions'])} |")
    L += ["", "### Alphabets", "", "*Each distinct alphabet once, with the languages that use it. The base reading is shown only where it differs from the letters reading (its positions joined by `·`; a position's other forms after `/`).*", ""]
    alph = [g for g in givens.values() if g["kind"] == "alphabet"]
    letters = {(g["script"], g["case"], json.dumps(g["positions"], ensure_ascii=False)): g for g in alph if g["reading"] == "letters"}
    base_by_lang = collections.defaultdict(dict)
    for g in alph:
        if g["reading"] == "base":
            for lg in g["languages"]:
                base_by_lang[(g["script"], g["case"])][lg] = g
    for script in sorted({g["script"] for g in alph}):
        gs = sorted((g for g in letters.values() if g["script"] == script), key=lambda g: (g["case"], -len(g["languages"]), json.dumps(g["positions"], ensure_ascii=False)))
        L += [f"#### {script} ({len(gs)})", "", "| case | languages | n | letters | base reading, where it differs |", "|---|---|---|---|---|"]
        for g in gs:
            b = base_by_lang[(script, g["case"])].get(g["languages"][0])
            bd = ""
            if b and len(b["positions"]) != len(g["positions"]):
                bd = code(" · ".join(p[0] + ("/" + "".join(p[1:]) if len(p) > 1 else "") for p in b["positions"][:SHOW_MAX])) + (" …" if len(b["positions"]) > SHOW_MAX else "")
            langs = ", ".join(g["languages"])
            L.append(f"| {g['case']} | {langs} | {len(g['positions']):,} | {seq(g['positions'])} | {bd} |")
        L.append("")
    L += ["### Dresses of letters", "", "*Every letter style and the base letters it holds, in base order. Their alphabets are the ones above; a dressed run is a walk over the alphabet holding its base letters.*", "",
          "| dress | letters | glyphs |", "|---|---|---|"]
    per = collections.defaultdict(list)
    for ch, (base, dn) in dress.items():
        per[dn].append((base, ch))
    for dn, xs in sorted(per.items(), key=lambda kv: (-len(kv[1]), kv[0])):
        xs.sort()
        L.append(f"| {dn} | {len(xs)} | {code(''.join(ch for _, ch in xs[:SHOW_MAX]))}{' …' if len(xs) > SHOW_MAX else ''} |")
    (ROOT / "CATALOG-GIVEN.md").write_text("\n".join(L) + "\n")
    print(f"CATALOG-GIVEN.md: {len(givens)} givens; {len(rows)} given-walk records, {sum(by_kind_rec.values())} recognised")

if __name__ == "__main__":
    main()
