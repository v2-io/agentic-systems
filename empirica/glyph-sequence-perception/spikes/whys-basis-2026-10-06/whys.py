#!/usr/bin/env python3
"""What the saved whys cite (RUBRIC.md, frozen before computing). Reads data/answers/c*.jsonl; writes REPORT.md beside
this file. Lexicon version: whys-rubric-v1."""
import collections, glob, json, pathlib, random, re

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parents[1]
VERSION = "whys-rubric-v1"

LEXICON = {
    "CHART": [r"unicode", r"code ?point", r"\bu\+[0-9a-f]{3,}", r"\bblock", r"encoding", r"char(acter)? ?set",
              r"(consecutive|sequential|adjacent)\W+(\w+\W+){0,3}?(code|char|character|unicode|point)"],
    "NAME": [r"letter", r"alphabet", r"digit", r"number", r"numeral", r"roman", r"greek", r"latin", r"cyrillic",
             r"hebrew", r"arabic", r"kana", r"hiragana", r"katakana", r"count", r"\bvalue", r"\bhour", r"o'clock",
             r"clock", r"\bmoon", r"phase", r"\bface", r"emoji", r"weather", r"\bnamed", r"\bcalled", r"stands for",
             r"represents", r"\bmeans\b", r"symbol for"],
    "LOOK": [r"shape", r"\bfill", r"filled", r"thick", r"\bthin", r"weight", r"\bbold", r"\bsize", r"height", r"\btall",
             r"width", r"\bwide", r"\bgrow", r"shrink", r"larger", r"smaller", r"bigger", r"rotat", r"orient",
             r"direction", r"pointing", r"\bdot", r"stroke", r"\bline", r"\bbar", r"curve", r"angle", r"visual",
             r"\blook", r"appear", r"\bdark", r"\blight", r"shade", r"dens", r"solid", r"hollow", r"outline", r"stack",
             r"layer", r"\bbend", r"straight", r"circle", r"square", r"triangle"],
}
RX = {k: [re.compile(p) for p in v] for k, v in LEXICON.items()}

def cats(why):
    w = (why or "").lower()
    return {k for k, ps in RX.items() if any(p.search(w) for p in ps)}

def chart_class(g):
    o = [ord(c) for c in g]
    d = [b - a for a, b in zip(o, o[1:])]
    if d and (all(x == 1 for x in d) or all(x == -1 for x in d)):
        return "contiguous"
    if d and (all(x > 0 for x in d) or all(x < 0 for x in d)):
        return "monotone"
    return "other"

def main():
    rows = []
    for f in sorted(glob.glob(str(ROOT / "data" / "answers" / "c*.jsonl"))):
        for l in open(f):
            r = json.loads(l)
            if r.get("why") and r["kind"] in ("cohere", "pick"):
                rows.append(r)
    L = [f"# What the whys cite: results ({VERSION})", "",
         f"*Generated by `whys.py` from `data/answers/c*.jsonl` under the frozen rubric (`RUBRIC.md`). {len(rows)} whys read.*", ""]
    # ---- cohere
    tab = collections.defaultdict(collections.Counter)
    for r in rows:
        if r["kind"] != "cohere" or r["outcome"] not in ("yes", "no"):
            continue
        ctl = r["tags"].get("control")
        typ = {None: "real", "shuffled": "shuffled", "chart": "chart-window"}.get(ctl, ctl) + "-" + r["outcome"]
        key = (r["family"], typ, chart_class(r["context"]))
        c = cats(r["why"])
        tab[key]["n"] += 1
        for k in ("CHART", "NAME", "LOOK"):
            tab[key][k] += k in c
        tab[key]["none"] += not c
    L += ["## Cohere whys", "", "| family | answer | chart class of the run shown | n | CHART | NAME | LOOK | none |", "|---|---|---|---|---|---|---|---|"]
    for key in sorted(tab):
        t = tab[key]
        if t["n"] < 10:
            continue
        L.append(f"| {key[0]} | {key[1]} | {key[2]} | {t['n']} | " + " | ".join(f"{t[k] / t['n']:.2f}" for k in ("CHART", "NAME", "LOOK", "none")) + " |")
    L += ["", "*Shares of whys citing each category (multi-label). Chart class: contiguous = every step ±1 code point; monotone = strictly monotone, not contiguous; other = neither.*", ""]
    # ---- picks
    pk = collections.defaultdict(collections.Counter)
    for r in rows:
        if r["kind"] != "pick" or r["outcome"] != "continuation":
            continue
        x, last = r["continuation"][0], r["context"][-1]
        adj = abs(ord(x) - ord(last)) == 1
        c = cats(r["why"])
        grp = ("CHART" if "CHART" in c else
               "LOOK, no CHART" if "LOOK" in c else
               "NAME, no CHART" if "NAME" in c else "none")
        key = (r["family"], "null" if r["tags"].get("null") else "real", grp)
        pk[key]["n"] += 1; pk[key]["adj"] += adj
    L += ["## Picks: does the reason track the behaviour?", "", "| family | contexts | the why cites | n | chart-adjacent picks |", "|---|---|---|---|---|"]
    for key in sorted(pk):
        t = pk[key]
        L.append(f"| {key[0]} | {key[1]} | {key[2]} | {t['n']} | {t['adj'] / t['n']:.2f} |" if t["n"] else "")
    L += ["", "*Chart-adjacent: the picked glyph is ±1 code point from the last glyph shown. If self-report tracks behaviour, picks whose why cites CHART are chart-adjacent far more often than the others.*", ""]
    # ---- samples
    r_ = random.Random(VERSION)
    L += ["## Samples, for checking the classification by eye", ""]
    for k in ("CHART", "NAME", "LOOK"):
        hit = [r for r in rows if k in cats(r["why"])]
        r_.shuffle(hit)
        L += [f"### {k} (20 of {len(hit)})", ""]
        L += [f"- `{' '.join(r['context'])[:40]}` ({r['kind']}, {r['family']}): {r['why'][:160].replace('|', '/')}" for r in hit[:20]]
        L.append("")
    (HERE / "REPORT.md").write_text("\n".join(L) + "\n")
    print("\n".join(L[:4]))

if __name__ == "__main__":
    main()
